# ============================================================
# OPTIMIZATION SUMMARY BUILDER
# ============================================================

def build_optimization_summary(
    optimization_machine: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build an executive optimization summary from the existing
    machine-level optimization opportunity file.
    """

    df = optimization_machine.copy()

    numeric_columns = [
        "Energy_kWh",
        "Optimized_Total_Reduction_kWh",
        "Potential_Reduction_Percent",
    ]

    for column in numeric_columns:
        if column in df.columns:
            df[column] = pd.to_numeric(
                df[column],
                errors="coerce",
            )

    current_energy = (
        df["Energy_kWh"].sum()
        if "Energy_kWh" in df.columns
        else 0
    )

    potential_reduction = (
        df["Optimized_Total_Reduction_kWh"].sum()
        if "Optimized_Total_Reduction_kWh" in df.columns
        else 0
    )

    optimized_energy = (
        current_energy - potential_reduction
    )

    reduction_percent = (
        potential_reduction / current_energy * 100
        if current_energy > 0
        else 0
    )

    emission_factor = float(
        os.getenv(
            "SYNTHETIC_EMISSION_FACTOR",
            "0.7",
        )
    )

    co2_reduction = (
        potential_reduction * emission_factor
    )

    return pd.DataFrame(
        [
            {
                "Metric": "Current Energy",
                "Value": current_energy,
            },
            {
                "Metric": "Optimized Model Energy",
                "Value": optimized_energy,
            },
            {
                "Metric": "Potential Energy Reduction",
                "Value": potential_reduction,
            },
            {
                "Metric": "Potential Reduction",
                "Value": reduction_percent,
            },
            {
                "Metric": "Potential CO2e Reduction",
                "Value": co2_reduction,
            },
        ]
    )


# ============================================================
# GENERATE ALL OUTPUTS
# ============================================================

def generate_outputs(
    outputs: dict[str, pd.DataFrame],
) -> None:
    """Generate all management-level analytical outputs."""

    logger.info(
        "Building optimization executive summary..."
    )

    optimization_summary = build_optimization_summary(
        outputs["optimization_machine"]
    )

    save_csv(
        optimization_summary,
        "optimization_executive_summary.csv",
    )

    logger.info(
        "Generating machine priority analysis..."
    )

    machine_priorities = identify_machine_priorities(
        outputs["machine_sustainability"],
        outputs["optimization_machine"],
    )

    save_csv(
        machine_priorities,
        "machine_priority_analysis.csv",
    )

    logger.info(
        "Generating executive KPI summary..."
    )

    kpi_summary = create_kpi_summary(
        baseline_summary=outputs["baseline_summary"],
        inefficiency_summary=outputs["inefficiency_summary"],
        forecast_summary=outputs["forecast_summary"],
        what_if_summary=outputs["what_if_summary"],
        optimization_summary=optimization_summary,
        co2_kpi=outputs["co2_kpi"],
    )

    save_csv(
        kpi_summary,
        "executive_kpi_summary.csv",
    )

    logger.info(
        "Generating management recommendations..."
    )

    recommendations = create_recommendations(
        machine_priorities,
        kpi_summary,
    )

    save_csv(
        recommendations,
        "management_recommendations.csv",
    )

    logger.info(
        "Generating implementation roadmap..."
    )

    roadmap = create_implementation_roadmap()

    save_csv(
        roadmap,
        "implementation_roadmap.csv",
    )

    logger.info(
        "Generating executive insights..."
    )

    executive_insights = create_executive_message(
        machine_priorities
    )

    save_csv(
        executive_insights,
        "executive_insights.csv",
    )

    logger.info(
        "Running recommendation validation..."
    )

    validation = validate_recommendation_outputs(
        machine_priorities,
        recommendations,
        roadmap,
    )

    save_csv(
        validation,
        "recommendation_validation.csv",
    )

    display_summary(
        machine_priorities,
        recommendations,
        optimization_summary,
        validation,
    )


